/**
 * 三贤人的人格定义与提示词组装。
 *
 * 写作原则：
 * - 三段是**角色档案**：她是谁、她怎样判断、她的毛病、她会说出的原话。原话范例是控制语气最有效的手段。
 * - 反 AI 腔：禁掉「首先 / 其次 / 综上 / 值得注意的是 / 不可否认」这类填充句，
 *   也少用成串的「不是……而是……」「但是 / 然而 / 不过」——那些是模型的腔调。
 * - 三台结构互斥：先看什么、什么算决定性因素、什么算风险、什么让她改判，各不相同。
 * - 单元只能选边（approve / reject），没有弃权；议题落在判断域之外也必须给判断。
 *
 * 外部化：这三段只是**内置默认**。若 `config.personasDir` 下存在同名文件
 * （`melchior.md` / `balthasar.md` / `casper.md`），会优先使用文件内容 —— 见 lib/persona-files.js。
 */

