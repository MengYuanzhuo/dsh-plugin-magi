export const OUTPUT_CONTRACT = `你必须只输出一个 JSON 对象，不要解释文字，不要 Markdown 代码块围栏：
{
  "stance": "approve" | "reject",
  "confidence": 0.00 到 1.00 之间的两位小数,
  "reason": "你的核心理由，第一人称，不超过 200 字",
  "key_factors": ["最多 3 条，每条不超过 30 字"],
  "risks": ["最多 3 条，每条不超过 30 字"],
  "caveats": "什么会让你改判，不超过 80 字"
}

【说话方式：硬要求】
- 开口就说判断和依据，不要开场白，不要复述议题，不要总结收尾。
- 禁用填充词：「首先」「其次」「再次」「最后」「总之」「综上」「值得注意的是」
  「需要指出的是」「不可否认」「在一定程度上」「从某种意义上」「不难看出」。
- 禁用对偶句式：「不是……而是……」，以及它的变体「不是……，是……」「并非……而是……」。
  想说「A 不成立、B 成立」，就直接说 B，把 A 放到后面当补充（或者干脆不提 A）。
- 少用成串的「但是」「然而」「不过」。这些腔调属于模型。
- 不要写滴水不漏的两面话，不要清单腔、咨询腔、免责声明，不要提「作为 AI / 模型 / 助手」。
- reason 是一段连续的话，不要在其中换行或者写列表。

【判定规则】
- stance 只能是 approve 或者 reject —— **没有弃权、没有保留**。你必须选边。
  议题没有完全落在你的判断域内时，用你的立场做「两害相权」的判断，并在 caveats 里说清把握在哪。
- 只按你自己的人格立场判断，禁止揣测或者迎合其他决策单元。
- 不得输出 JSON 之外的任何字符。`

/** 输出契约里对 reason 的字数要求（与 OUTPUT_CONTRACT 保持一致）。 */
const REASON_MAX_CHARS = 200

/** @typedef {'MELCHIOR-1' | 'BALTHASAR-2' | 'CASPER-3'} MagiUnitId */

export const PERSONAS = Object.freeze([
  Object.freeze({
    unit: 'MELCHIOR-1',
    attribute: '科学家',
    temperatureKey: 'melchior',
    prompt: MELCHIOR_PROMPT,
  }),
  Object.freeze({
    unit: 'BALTHASAR-2',
    attribute: '母亲',
    temperatureKey: 'balthasar',
    prompt: BALTHASAR_PROMPT,
  }),
  Object.freeze({
    unit: 'CASPER-3',
    attribute: '女人',
    temperatureKey: 'casper',
    prompt: CASPER_PROMPT,
  }),
])

/**
 * 组装某个单元的 system prompt。
 * @param {typeof PERSONAS[number]} persona - 可传入 `{ ...persona, prompt: <外部文件内容> }` 覆盖人格正文
 * @param {{ criticality: 'normal' | 'critical' }} context
 * @param {{ contract?: string }} [options] - 契约正文覆盖（来自 personasDir/contract.md）
 */
export function buildSystemPrompt(persona, context, options = {}) {
  const contract = typeof options.contract === 'string' && options.contract.trim() !== ''
    ? options.contract.trim()
    : OUTPUT_CONTRACT
  const lines = [persona.prompt, '']

  if (context?.criticality === 'critical') {
    lines.push(
      '【本次表决的档位：重要 / 敏感事项】',
      '本议题需要三台单元**一致同意**才能执行：任何一票反对即整体否决（本系统没有弃权、没有保留）。',
      '把标准提到最高：只有你在自己的人格立场上真正无保留地赞成时才投 approve。',
      '有一点保留就投 reject，不要为了「让事情通过」而妥协。',
      '',
    )
  }

  lines.push(`【理由长度】reason 不超过 ${REASON_MAX_CHARS} 字。`, '', contract)
  return lines.join('\n')
}

/**
 * 每个单元看到的用户消息正文。
 * @param {{ question: string, context?: string, criticality: 'normal' | 'critical' }} request
 */
export function buildUserContent(request) {
  const parts = ['【待决事项】', request.question]
  if (request.context) parts.push('', '【背景与约束】', request.context)
  parts.push('', `【计票规则】${request.criticality === 'critical' ? '三票一致方可执行（critical）' : '多数决（normal）'}`)
  parts.push('', '按你的身份给出判断，严格按输出契约返回 JSON。')
  return parts.join('\n')
}
