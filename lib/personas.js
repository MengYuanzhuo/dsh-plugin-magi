/**
 * 组装某个单元的 system prompt。
 * @param {typeof PERSONAS[number]} persona - 可传入 `{ ...persona, prompt: <外部文件内容> }` 覆盖人格正文
 * @param {{ criticality: 'normal' | 'critical' }} context
 * @param {{ contract?: string, abilities?: string }} [options] - 契约正文覆盖（来自 personasDir/contract.md）；abilities 为该单元子功能说明
 */
export function buildSystemPrompt(persona, context, options = {}) {
  const contract = typeof options.contract === 'string' && options.contract.trim() !== ''
    ? options.contract.trim()
    : OUTPUT_CONTRACT
  const lines = [persona.prompt, '']

  if (context?.criticality === 'critical') {
    lines.push(
      '【本次表决的档位：重要 / 敏感事项】',
      '本议题需要三台单元**一致同意**才能执行：任何一票反对即整体否决（本系统没有弃权、没有保留）。',
      '把标准提到最高：只有你在自己的人格立场上真正无保留地赞成时才投 approve。',
      '有一点保留就投 reject，不要为了「让事情通过」而妥协。',
      '',
    )
  }

  lines.push(`【理由长度】reason 不超过 ${REASON_MAX_CHARS} 字。`, '', contract)
  if (typeof options.abilities === 'string' && options.abilities.trim() !== '') {
    lines.push('', options.abilities.trim())
  }
  return lines.join('\n')
}

/**
 * 每个单元看到的用户消息正文。
 * @param {{ question: string, context?: string, criticality: 'normal' | 'critical' }} request
 */
export function buildUserContent(request) {
  const parts = ['【待决事项】', request.question]
  if (request.context) parts.push('', '【背景与约束】', request.context)
  parts.push('', `【计票规则】${request.criticality === 'critical' ? '三票一致方可执行（critical）' : '多数决（normal）'}`)
  parts.push('', '按你的身份给出判断，严格按输出契约返回 JSON。')
  return parts.join('\n')
}
